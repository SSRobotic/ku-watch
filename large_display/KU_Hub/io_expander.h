/**
 * ==========================================================================
 *  io_expander.h
 *  ไดรเวอร์สำหรับชิป TCA9554 (I2C GPIO Expander) ที่แอดเดรส 0x20
 * --------------------------------------------------------------------------
 *  ทำไมต้องมีไฟล์นี้:
 *    ขาสำคัญหลายตัวของบอร์ดนี้ไม่ได้ต่อกับ ESP32 โดยตรง แต่ต่อผ่าน TCA9554
 *    โดยเฉพาะ SD_CS (EXIO4) ที่เราต้องใช้ตอนเปิด SD card ใน Step 3
 *
 *    ดังนั้น  digitalWrite(SD_CS, LOW)  ใช้ไม่ได้
 *    ต้องเป็น IOExpander::setPin(EXIO_SD_CS, false)  แทน
 * ==========================================================================
 */

#pragma once
#include <Arduino.h>
#include <stdint.h>

namespace IOExpander {

/**
 * เริ่มต้นใช้งานชิป TCA9554
 * - ตั้งทิศทางขา: EXIO5/6/7 เป็นอินพุต (ขาสัญญาณจาก IMU และ RTC)
 *                  ที่เหลือเป็นเอาต์พุต
 * - ตั้งค่าเริ่มต้นที่ปลอดภัย: CS ทุกตัวเป็น HIGH (ไม่เลือกอุปกรณ์)
 *                              รีเซ็ตทุกตัวเป็น HIGH (ไม่รีเซ็ต)
 *                              บัซเซอร์เป็น LOW (เงียบ)
 *
 * @return true ถ้าคุยกับชิปได้สำเร็จ
 */
bool begin();

/**
 * สั่งขาเอาต์พุตหนึ่งขา
 * @param exio  หมายเลข EXIO 1..8 (ใช้ค่าคงที่จาก board_pins.h)
 * @param high  true = HIGH, false = LOW
 */
bool setPin(uint8_t exio, bool high);

/**
 * อ่านสถานะขาจริง ๆ จากชิป (อ่านได้ทั้งขาอินพุตและเอาต์พุต)
 * @param exio   หมายเลข EXIO 1..8
 * @param value  ตัวแปรรับค่า
 */
bool readPin(uint8_t exio, bool &value);

/**
 * อ่านค่าที่เราสั่งไปล่าสุด (shadow register ในหน่วยความจำ)
 * ใช้ตรวจสอบว่าโค้ดเราคิดว่าขาเป็นอะไรอยู่
 */
uint8_t outputShadow();

/**
 * ทดสอบตัวเองว่าเขียน/อ่านกลับได้ถูกต้องไหม
 * ใช้ขา EXIO_SD_CS ในการทดสอบ (ปลอดภัยเพราะยังไม่ได้เปิด SD card)
 * @return true ถ้าเขียนแล้วอ่านกลับมาตรงกันทุกครั้ง
 */
bool selfTest();

} // namespace IOExpander
